// Maps SmartSpectra metric samples to the SiteGuard reading contract
// (docs/PRESAGE_CONTRACT.md, packages/contracts/src/models.ts VitalReadingSchema).
//
// Pure Swift with no SDK import so it is unit-testable on its own. Mirrors the
// Presage bridge's mapping (integrations/presage-bridge/src/adapters/presage-sdk.ts
// statusFromStable and src/normalize.ts):
//   - validity comes ONLY from the SDK's explicit `stable` flag
//     (docs/data-types.md: "Whether the measurement is considered
//     stable/reliable"; pulse stable <=> confidence >= 40, breathing >= 45):
//       stable == true -> valid, stable == false -> invalid, absent -> unknown
//   - the numeric value never upgrades or downgrades validity, except that a
//     "valid" sample with no usable positive finite number becomes unknown;
//   - when pulse and breathing validity differ, separate readings are emitted
//     with the other rate null.
// The shared fixture SiteGuardCheckInTests/Fixtures/mapped-readings.json is
// also checked in TypeScript against the contract schema and the bridge.
import Foundation

enum ReadingQuality: String, Codable, Equatable {
    case valid, invalid, unknown
}

/// One SDK sample, reduced to the documented fields SiteGuard uses.
/// `timestampMicros` is microseconds since the Unix epoch (docs/data-types.md).
struct MetricSample: Equatable {
    var value: Double?
    var stable: Bool?
    var timestampMicros: Int64
}

/// SiteGuard VitalReading. The phone app only ever produces real Presage
/// readings; synthetic readings are generated by the SiteGuard server only.
struct VitalReading: Codable, Equatable {
    var timestamp: String
    var heartRateBpm: Double?
    var respiratoryRateBrpm: Double?
    var quality: ReadingQuality
    var source: String = "presage"

    enum CodingKeys: String, CodingKey {
        case timestamp, heartRateBpm, respiratoryRateBrpm, quality, source
    }

    // The contract uses strict objects with explicit nulls, so nil rates are
    // encoded as JSON null instead of being omitted (the synthesized default).
    func encode(to encoder: Encoder) throws {
        var c = encoder.container(keyedBy: CodingKeys.self)
        try c.encode(timestamp, forKey: .timestamp)
        if let heartRateBpm { try c.encode(heartRateBpm, forKey: .heartRateBpm) } else {
            try c.encodeNil(forKey: .heartRateBpm)
        }
        if let respiratoryRateBrpm {
            try c.encode(respiratoryRateBrpm, forKey: .respiratoryRateBrpm)
        } else {
            try c.encodeNil(forKey: .respiratoryRateBrpm)
        }
        try c.encode(quality, forKey: .quality)
        try c.encode(source, forKey: .source)
    }
}

/// `{sequence, reading}` as accepted by `POST /api/sessions/:id/readings`.
struct ReadingEnvelope: Codable, Equatable {
    var sequence: Int
    var reading: VitalReading
}

enum ReadingMapper {
    static func quality(stable: Bool?) -> ReadingQuality {
        switch stable {
        case .some(true): return .valid
        case .some(false): return .invalid
        case .none: return .unknown
        }
    }

    static func rate(_ value: Double?) -> Double? {
        guard let value, value.isFinite, value > 0 else { return nil }
        return value
    }

    static func quality(of sample: MetricSample) -> ReadingQuality {
        let q = quality(stable: sample.stable)
        return q == .valid && rate(sample.value) == nil ? .unknown : q
    }

    private static let formatter: ISO8601DateFormatter = {
        let f = ISO8601DateFormatter()
        f.formatOptions = [.withInternetDateTime, .withFractionalSeconds]
        f.timeZone = TimeZone(identifier: "UTC")
        return f
    }()

    /// UTC ISO-8601 with milliseconds, e.g. 2026-10-10T15:00:01.000Z.
    static func isoTimestamp(micros: Int64) -> String {
        formatter.string(from: Date(timeIntervalSince1970: Double(micros) / 1_000_000))
    }

    static func normalize(pulse: MetricSample?, breathing: MetricSample?) -> [VitalReading] {
        func reading(_ hr: MetricSample?, _ rr: MetricSample?, _ q: ReadingQuality, _ ts: Int64)
            -> VitalReading
        {
            VitalReading(
                timestamp: isoTimestamp(micros: ts),
                heartRateBpm: rate(hr?.value),
                respiratoryRateBrpm: rate(rr?.value),
                quality: q
            )
        }
        switch (pulse, breathing) {
        case let (p?, b?):
            let qp = quality(of: p), qb = quality(of: b)
            if qp == qb && p.timestampMicros == b.timestampMicros {
                return [reading(p, b, qp, p.timestampMicros)]
            }
            return [
                reading(p, nil, qp, p.timestampMicros),
                reading(nil, b, qb, b.timestampMicros),
            ]
        case let (p?, nil):
            return [reading(p, nil, quality(of: p), p.timestampMicros)]
        case let (nil, b?):
            return [reading(nil, b, quality(of: b), b.timestampMicros)]
        case (nil, nil):
            return []
        }
    }
}

/// Turns SDK payloads into new readings only: a metric sample is forwarded
/// once, when its timestamp advances. Samples
/// without a positive timestamp are ignored (docs/swift/metrics.md filters
/// `timestamp > 0`). Sequence numbers start at 0 and increase by one.
struct ReadingCollector {
    private(set) var envelopes: [ReadingEnvelope] = []
    private var lastPulseMicros: Int64 = 0
    private var lastBreathingMicros: Int64 = 0

    mutating func ingest(pulse: MetricSample?, breathing: MetricSample?) -> [ReadingEnvelope] {
        let newPulse = pulse.flatMap { $0.timestampMicros > lastPulseMicros ? $0 : nil }
        let newBreathing = breathing.flatMap {
            $0.timestampMicros > lastBreathingMicros ? $0 : nil
        }
        if let newPulse { lastPulseMicros = newPulse.timestampMicros }
        if let newBreathing { lastBreathingMicros = newBreathing.timestampMicros }
        let added = ReadingMapper.normalize(pulse: newPulse, breathing: newBreathing)
            .enumerated()
            .map { ReadingEnvelope(sequence: envelopes.count + $0.offset, reading: $0.element) }
        envelopes.append(contentsOf: added)
        return added
    }

    /// Ingest every sample in a payload, not just each metric's last value.
    /// Rates are event-driven and multiple values can arrive between UI ticks.
    mutating func ingest(pulses: [MetricSample], breathings: [MetricSample]) -> [ReadingEnvelope] {
        let newPulses = pulses.filter { $0.timestampMicros > lastPulseMicros }
            .sorted { $0.timestampMicros < $1.timestampMicros }
        let newBreathings = breathings.filter { $0.timestampMicros > lastBreathingMicros }
            .sorted { $0.timestampMicros < $1.timestampMicros }
        var pulseIndex = 0
        var breathingIndex = 0
        var added: [ReadingEnvelope] = []
        while pulseIndex < newPulses.count || breathingIndex < newBreathings.count {
            let pulseTime = pulseIndex < newPulses.count
                ? newPulses[pulseIndex].timestampMicros : Int64.max
            let breathingTime = breathingIndex < newBreathings.count
                ? newBreathings[breathingIndex].timestampMicros : Int64.max
            let pulse = pulseTime <= breathingTime ? newPulses[pulseIndex] : nil
            let breathing = breathingTime <= pulseTime ? newBreathings[breathingIndex] : nil
            if pulse != nil { pulseIndex += 1 }
            if breathing != nil { breathingIndex += 1 }
            added += ingest(pulse: pulse, breathing: breathing)
        }
        return added
    }

    var validPulseCount: Int {
        envelopes.filter { $0.reading.quality == .valid && $0.reading.heartRateBpm != nil }.count
    }
    var validBreathingCount: Int {
        envelopes.filter { $0.reading.quality == .valid && $0.reading.respiratoryRateBrpm != nil }
            .count
    }
}
